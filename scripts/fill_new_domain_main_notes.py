def replace_section(text: str, heading: str, next_re: str, body: list) -> str:
    lines = text.split('\n')
    try:
        i = next(k for k, l in enumerate(lines) if l.strip() == heading)
    except StopIteration:
        raise ValueError(f'章节不存在: {heading}')
    j = i + 1
    while j < len(lines) and not re.match(next_re, lines[j]):
        j += 1
    if j >= len(lines):
        raise ValueError(f'未找到后续章节: {next_re} (after {heading})')
    return '\n'.join(lines[:i + 1] + [''] + body + [''] + lines[j:])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--apply', action='store_true', help='实际写盘（默认仅 dry_run）')
    args = ap.parse_args()

    n_changed = 0
    for code, cfg in CONTENT.items():
        rel = op.main_note_rel_path(cfg['name'], cfg['group'])
        path = VAULT / rel.replace('\\', '/')
        if not path.exists():
            print(f'SKIP(no-file) {code} {rel}')
            continue
        before = path.read_text(encoding='utf-8')
        after = before
        for key, heading, nxt in SECTIONS:
            after = replace_section(after, heading, nxt, cfg[key])
        # 自动区零改动校验
        pat = re.compile(r'<!--\s*PMWB:AUTO:BEGIN\s+key=(\w+)\s*-->(.*?)<!--\s*PMWB:AUTO:END\s+key=\1\s*-->', re.S)
        assert [m.group(2) for m in pat.finditer(before)] == [m.group(2) for m in pat.finditer(after)], f'自动区被改动: {rel}'
        changed = after != before
        print(f'[{"WRITE" if changed else "NOOP"}] {code} {cfg["name"]} | {rel} | 自动区未变: 6块')
        if changed and args.apply:
            write_markdown(rel, after, protect_if_modified=False)
            n_changed += 1

    print(f'\n{"已写入" if args.apply else "待写入"}: {n_changed}/{len(CONTENT)}')


if __name__ == '__main__':
    main()
